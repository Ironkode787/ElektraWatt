/// The UUID of the device whose tag prints `tag`.
fn device(s: &Session, tag: &str) -> ew_derive::ew_ids::Uuid {
    s.resolve_reference(&format!("tag:{tag}")).unwrap()
}

fn row<'s>(sheet: &'s PropertySheet, key: &str) -> &'s ew_api::output::PropRow {
    sheet
        .sections
        .iter()
        .flat_map(|s| &s.rows)
        .find(|r| r.key == key)
        .unwrap_or_else(|| {
            let keys: Vec<&str> = sheet
                .sections
                .iter()
                .flat_map(|s| &s.rows)
                .map(|r| r.key.as_str())
                .collect();
            panic!("no row {key}: {keys:#?}")
        })
}

fn one(r: &ew_api::output::PropRow) -> &str {
    match &r.value {
        RowValue::One { text, .. } => text,
        other => panic!("{}: {other:?}", r.key),
    }
}

/// A representation of a device (its main one).
fn main_rep(s: &Session, device: ew_derive::ew_ids::Uuid) -> ew_derive::ew_ids::Uuid {
    let q = s.query();
    let id = ew_derive::ew_ids::Id::from_uuid(device);
    q.get::<ew_derive::MainRep>(id).unwrap().as_uuid()
}

/// The connection whose golden key is `key` (`W29`: the one on folio 103).
fn wire(s: &Session, key: &str) -> ew_derive::ew_ids::Uuid {
    let q = s.query();
    let want = format!("connections|{key}");
    q.connections()
        .iter()
        .find(|(_, c)| c.source_ref.as_ref().is_some_and(|r| r.key.as_str() == want))
        .map(|(id, _)| id.as_uuid())
        .unwrap_or_else(|| panic!("no connection {key}"))
}

/// The drawn page labelled `folio`.
fn page(s: &Session, folio: &str) -> ew_derive::ew_ids::Uuid {
    s.resolve_reference(&format!("folio:{folio}")).unwrap()
}

