//! Golden A's route tool (WP-S2.19 §8.2, decision log ID-1499): the routes of the page connections of folios 3, 101,
//! 102, 103 and 106 are the schematic router's. The tool imports the tables with those rows' routes left out, routes
//! each page with `Session::route_plan` (Route page), and writes each route's corners into `connections.csv`'s `route`
//! column in the column's grammar (`<cell>` or `<cell> <dx> <dy>`, QET px from the cell's centre); folio 203's hand
//! routes (U-51, FT-1315) are never rewritten. Compare mode asserts that the committed column is the router's result,
//! so a router change is a golden diff, and that every page connection is routed (RG1).
//!
//! The layout of the routed pages, the bends and crossings per page (RG3), is in `golden/J-E-2416/expected/layout.txt`:
//! a later change that raises a page's total fails, and no connection has more than four bends unless the file lists
//! it with its reason.
//!
//! Bless (the tables, then the layout file):
//! `EW_BLESS_GOLDEN_ROUTES=1 cargo nextest run -p ew-api --test it -E 'test(/^golden_routes::/)'`; then the
//! doc-20 generator keeps the committed routes (`tables_from_doc20.py --check` passes), and the fixture is
//! regenerated by `golden_fixture`'s bless test.

// The bless flag is an environment read; the tests read the committed tables directly.
#![allow(clippy::disallowed_methods)]

use crate::golden_common;

use std::collections::BTreeMap;
use std::path::PathBuf;

use ew_api::routing::{RouteScope, Unrouted};
use ew_derive::ew_units::{Grid, Nm};
use ew_import_tables::ew_interop_api::{ImportBatch, ImportInput};
use ew_import_tables::{TablesImporter, bootstrap_context};

/// The folios whose route-less page connections the router routes; folio 203's routes are hand-written.
const ROUTED: [&str; 5] = ["3", "101", "102", "103", "106"];

/// The frame grid of the golden pages in QET px (`ew-import-tables`' cell geometry): the header band, a column's
/// width, a row's height.
const HEADER_PX: i64 = 20;
const COLUMN_PX: i64 = 60;
const ROW_PX: i64 = 80;

fn bless() -> bool {
    std::env::var("EW_BLESS_GOLDEN_ROUTES").is_ok_and(|v| v == "1")
}

fn tables_dir() -> PathBuf {
    golden_common::repo().join("golden/J-E-2416/tables")
}

fn layout_path() -> PathBuf {
    golden_common::repo().join("golden/J-E-2416/expected/layout.txt")
}

/// The committed `connections.csv`: its lines (the header first).
fn connection_lines() -> Vec<String> {
    let text = std::fs::read_to_string(tables_dir().join("connections.csv")).expect("connections.csv");
    text.lines().map(str::to_owned).collect()
}

/// The column index of `name` in the header line.
fn column(header: &str, name: &str) -> usize {
    header
        .split(',')
        .position(|c| c == name)
        .unwrap_or_else(|| panic!("connections.csv has a `{name}` column"))
}

/// Whether a `connections.csv` line is a page connection of one of the [`ROUTED`] folios.
fn router_row(cells: &[&str], page: usize) -> bool {
    cells.get(page).is_some_and(|p| ROUTED.contains(p))
}

/// The golden tables with the router-written routes left out (`clear`) or as committed.
fn batch(clear: bool) -> ImportBatch {
    let mut paths: Vec<PathBuf> = std::fs::read_dir(tables_dir())
        .expect("the golden tables")
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "csv"))
        .collect();
    paths.sort();
    let inputs: Vec<ImportInput> = paths
        .iter()
        .map(|p| {
            let name = p.file_name().unwrap().to_string_lossy().into_owned();
            let mut bytes = std::fs::read(p).unwrap();
            if clear && name == "connections.csv" {
                let lines = connection_lines();
                let (page, route) = (column(&lines[0], "page"), column(&lines[0], "route"));
                let mut out = Vec::new();
                for (i, line) in lines.iter().enumerate() {
                    let mut cells: Vec<&str> = line.split(',').collect();
                    if i > 0 && router_row(&cells, page) {
                        cells[route] = "";
                    }
                    out.push(cells.join(","));
                }
                bytes = (out.join("\n") + "\n").into_bytes();
            }
            ImportInput::new(&name, bytes).unwrap()
        })
        .collect();
    TablesImporter::new(golden_common::library())
        .import(&inputs, &bootstrap_context())
        .expect("the golden tables import")
}

/// One coordinate of a corner in QET px: its own px when it is a whole px, else the px of the end coordinate it
/// equals (the importer gives a corner that names an end's px the end's exact value).
fn px_of(v: i64, ends: [i64; 2]) -> Result<i64, String> {
    let px = Grid::QET_1PX;
    let k = px.snap(Nm(v));
    if px.at(k) == Some(Nm(v)) || ends.contains(&v) {
        Ok(k)
    } else {
        Err(format!("the corner coordinate {v} nm is no whole QET px"))
    }
}

/// A corner in the `route` grammar: its cell (the one whose centre is nearest along each axis, within the frame's
/// rows A–H and columns 0–16) and its offset in QET px from that cell's centre.
fn corner_cell(p: (i64, i64), a: (i64, i64), b: (i64, i64)) -> Result<String, String> {
    let (x, y) = (px_of(p.0, [a.0, b.0])?, px_of(p.1, [a.1, b.1])?);
    let col = (x - HEADER_PX).div_euclid(COLUMN_PX).clamp(0, 16);
    let row = (y - HEADER_PX).div_euclid(ROW_PX).clamp(0, 7);
    let dx = x - (HEADER_PX + COLUMN_PX * col + COLUMN_PX / 2);
    let dy = y - (HEADER_PX + ROW_PX * row + ROW_PX / 2);
    let letter = char::from(b'A' + u8::try_from(row).unwrap_or(0));
    Ok(if (dx, dy) == (0, 0) {
        format!("{letter}{col}")
    } else {
        format!("{letter}{col} {dx} {dy}")
    })
}

/// What the router gives Golden A: the `route` cell of each routed row by key, and the rows left unrouted with their
/// reasons (`folio key reason`).
fn router_routes() -> (BTreeMap<String, String>, Vec<String>) {
    let batch = batch(true);
    let s = golden_common::session(&batch);
    let key_of: BTreeMap<String, String> = golden_common::ids_by_key(&batch)
        .into_iter()
        .filter_map(|(k, id)| k.strip_prefix("connections|").map(|k| (id, k.to_owned())))
        .collect();
    let mut routes = BTreeMap::new();
    let mut unrouted = Vec::new();
    for folio in ROUTED {
        let plan = s
            .route_plan(folio, &RouteScope::Page)
            .unwrap_or_else(|| panic!("folio {folio} is drawn"));
        for (id, route) in &plan.routes {
            let key = key_of
                .get(&id.to_string())
                .cloned()
                .unwrap_or_else(|| id.to_string());
            let (a, b) = (route[0], route[route.len() - 1]);
            let cells: Result<Vec<String>, String> = route[1..route.len() - 1]
                .iter()
                .map(|p| corner_cell(*p, a, b))
                .collect();
            match cells {
                Ok(cells) => {
                    routes.insert(key, cells.join(";"));
                }
                Err(e) => panic!("folio {folio}, {key}: {e} (route {route:?})"),
            }
        }
        for (id, why) in &plan.unrouted {
            let key = key_of
                .get(&id.to_string())
                .cloned()
                .unwrap_or_else(|| id.to_string());
            let words = s.connection_words(folio, *id).unwrap_or_default();
            let why = match why {
                Unrouted::Wires => "wires",
                Unrouted::Symbols => "symbols",
                Unrouted::Texts => "texts",
                Unrouted::Points => "points",
                Unrouted::FourArms => "four arms",
            };
            unrouted.push(format!("{folio} {key} ({words}): {why}"));
        }
    }
    (routes, unrouted)
}

/// The committed `route` cells of the router's rows, by key.
fn committed_routes() -> BTreeMap<String, String> {
    let lines = connection_lines();
    let (key, page, route) = (
        column(&lines[0], "key"),
        column(&lines[0], "page"),
        column(&lines[0], "route"),
    );
    lines[1..]
        .iter()
        .map(|l| l.split(',').collect::<Vec<_>>())
        .filter(|c| router_row(c, page) && !c[route].is_empty())
        .map(|c| (c[key].to_owned(), c[route].to_owned()))
        .collect()
}

/// Writes `routes` into the router's rows of `connections.csv` (every other byte kept).
fn write_routes(routes: &BTreeMap<String, String>) {
    let lines = connection_lines();
    let (key, page, route) = (
        column(&lines[0], "key"),
        column(&lines[0], "page"),
        column(&lines[0], "route"),
    );
    let mut out = Vec::new();
    for (i, line) in lines.iter().enumerate() {
        let mut cells: Vec<String> = line.split(',').map(str::to_owned).collect();
        if i > 0 && router_row(&cells.iter().map(String::as_str).collect::<Vec<_>>(), page) {
            cells[route] = routes.get(&cells[key]).cloned().unwrap_or_default();
        }
        out.push(cells.join(","));
    }
    std::fs::write(tables_dir().join("connections.csv"), out.join("\n") + "\n")
        .expect("writing connections.csv");
}

/// The layout of Golden A as committed, per routed page: the hard-rule total, crossings and bends, then each
/// connection with more than four bends (RG3).
fn layout_text() -> String {
    let s = golden_common::session(&batch(false));
    let mut out = String::from(
        "# Golden A's layout per routed page (WP-S2.19 RG3): written by golden_routes' bless; a page's totals never \
         rise.\n",
    );
    let mut folios: Vec<&str> = ROUTED.to_vec();
    folios.push("203");
    for folio in folios {
        let pages = s.layout_report(Some(folio)).expect("a drawn page");
        for p in &pages {
            out.push_str(&format!(
                "{}: hard {}, crossings {}, bends {}\n",
                p.folio,
                p.hard(),
                p.crossings.len(),
                p.bend_total()
            ));
            for b in p.bends.iter().filter(|b| b.bends > 4) {
                out.push_str(&format!("  {} bends: {}\n", b.bends, b.connection));
            }
        }
    }
    out
}

/// The per-page totals of a layout text: folio → (hard, crossings, bends).
fn totals(text: &str) -> BTreeMap<String, (usize, usize, usize)> {
    text.lines()
        .filter(|l| !l.starts_with('#') && !l.starts_with(' '))
        .filter_map(|l| {
            let (folio, rest) = l.split_once(": ")?;
            let n: Vec<usize> = rest
                .split(", ")
                .filter_map(|part| part.rsplit(' ').next()?.parse().ok())
                .collect();
            let [hard, crossings, bends] = n.as_slice() else {
                return None;
            };
            Some((folio.to_owned(), (*hard, *crossings, *bends)))
        })
        .collect()
}

#[test]
fn golden_a_routes_are_the_router_s() {
    let (routes, unrouted) = router_routes();
    if bless() {
        write_routes(&routes);
        std::fs::write(layout_path(), layout_text()).expect("writing layout.txt");
    }
    assert_eq!(
        unrouted,
        Vec::<String>::new(),
        "RG1: every page connection is routed"
    );
    assert_eq!(
        committed_routes(),
        routes,
        "the committed routes are the router's (bless with EW_BLESS_GOLDEN_ROUTES=1)"
    );
}

#[test]
fn golden_a_layout_never_gets_worse() {
    if bless() {
        return;
    }
    let committed = std::fs::read_to_string(layout_path()).expect("golden/J-E-2416/expected/layout.txt");
    let now = layout_text();
    let (was, is) = (totals(&committed), totals(&now));
    assert_eq!(was.keys().collect::<Vec<_>>(), is.keys().collect::<Vec<_>>());
    for (folio, (hard, crossings, bends)) in &is {
        let (h0, c0, b0) = was[folio];
        assert!(
            *hard <= h0 && *crossings <= c0 && *bends <= b0,
            "folio {folio}: hard {hard}, crossings {crossings}, bends {bends} rise above {h0}, {c0}, {b0}"
        );
    }
    // A connection with more than four bends is listed with the file's review.
    for line in now.lines().filter(|l| l.starts_with("  ")) {
        assert!(
            committed.lines().any(|l| l == line),
            "not listed in layout.txt: {line}"
        );
    }
}
