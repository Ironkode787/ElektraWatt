//! Command metadata (doc 17 §2.1, §2.3): cost, exposure class, stability, confirmation and the origin of a
//! transaction.

use serde::{Deserialize, Serialize};

/// How a command runs (ARCH §5.1).
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Cost {
    /// Runs on the interactive path: `Session::execute`.
    #[default]
    Interactive,
    /// Always runs as a preview on a fork first (ADR-0008); committed by `Session::commit`.
    Bulk,
}

/// Which front-ends may submit a command (doc 17 §2.3, FR-EXT-030).
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Exposure {
    /// GUI, CLI (`apply`), scripts, MCP, plugins and Python.
    Edit,
    /// The GUI, and a dedicated CLI subcommand confirmed on a terminal.
    HumanOnly,
    /// The import wizard and `ew import`.
    Import,
    /// Normalisers only; never submitted from outside.
    Internal,
}

impl Exposure {
    /// Whether an origin may submit a command of this class. `HumanOnly` is accepted from the GUI and
    /// from a CLI subcommand that a human confirmed on a terminal (`Origin::Cli { confirmed: true }`, D7),
    /// and refused for an unconfirmed CLI submission, command logs, scripts, MCP, plugins and Python;
    /// `Import` is accepted from the GUI, the CLI and an import origin; `Internal` from nobody.
    pub fn allows(self, origin: &Origin) -> bool {
        match self {
            Exposure::Edit => true,
            Exposure::HumanOnly => matches!(origin, Origin::Gui | Origin::Cli { confirmed: true, .. }),
            Exposure::Import => matches!(origin, Origin::Gui | Origin::Cli { .. } | Origin::Import { .. }),
            Exposure::Internal => false,
        }
    }
}

/// The stability promise of a command's name and parameters (doc 17 §2.1, §11).
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Stability {
    /// Frozen; a breaking parameter change bumps `params_version`.
    Stable,
    /// May change before 1.0 (every v0 command).
    Preview,
    /// Not part of the public catalogue.
    Internal,
}

/// Whether a front-end asks before submitting (ADR-0008 amendment 1, NFR-UX-07).
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Confirmation {
    /// No confirmation: the command is undoable, or a harmless marker line.
    #[default]
    None,
    /// A destructive non-undoable operation: library writes outside the project, overwriting a file,
    /// purging library copies, the empty-project import checkpoint.
    Destructive,
}

/// The registered metadata of one command type (doc 17 §2.1). The parameter schema is generated by the
/// registry from the command's `JsonSchema` implementation.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct CommandMeta {
    /// The stable dotted name, `[a-z_]+ "." [a-z_.]+`, never reused (FR-EXT-015).
    pub name: &'static str,
    /// Bumped only by a breaking parameter change.
    pub params_version: u16,
    /// The default cost; an instance may report another one (`edit.delete` above 500 records).
    pub cost: Cost,
    /// Whether the transaction enters the undo stack; otherwise it is a marker line.
    pub undoable: bool,
    /// The exposure class.
    pub exposure: Exposure,
    /// The stability level.
    pub stability: Stability,
    /// Retired names and palette aliases; they resolve to `name`, which the journal records.
    pub aliases: &'static [&'static str],
    /// Whether front-ends confirm before submitting.
    pub confirmation: Confirmation,
}

impl CommandMeta {
    /// The metadata of an undoable, interactive `Edit` command at `params_version` 1 and stability
    /// `Preview`, without aliases: the shape of every v0 editor command.
    pub const fn edit(name: &'static str) -> CommandMeta {
        CommandMeta {
            name,
            params_version: 1,
            cost: Cost::Interactive,
            undoable: true,
            exposure: Exposure::Edit,
            stability: Stability::Preview,
            aliases: &[],
            confirmation: Confirmation::None,
        }
    }

    /// The same metadata with cost `Bulk`.
    pub const fn bulk(self) -> CommandMeta {
        CommandMeta {
            cost: Cost::Bulk,
            ..self
        }
    }

    /// The same metadata with aliases.
    pub const fn with_aliases(self, aliases: &'static [&'static str]) -> CommandMeta {
        CommandMeta { aliases, ..self }
    }
}

/// Who submitted a transaction (doc 17 §2.3); shown in the history panel and written to the journal.
#[derive(Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Debug, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Origin {
    /// An editor gesture.
    #[default]
    Gui,
    /// An `ew` subcommand.
    Cli {
        /// The subcommand.
        subcommand: String,
        /// Whether a human confirmed the submission on a terminal (the dedicated subcommand of a
        /// `HumanOnly` command, doc 17 §2.3). Scripted CLI use leaves it `false`.
        #[serde(default)]
        confirmed: bool,
    },
    /// A replayed command log (`ew apply`).
    CmdLog {
        /// The log file name, relative to the project.
        file: String,
    },
    /// A rhai automation script.
    Script {
        /// The script name.
        name: String,
    },
    /// An MCP client.
    Mcp {
        /// The client name.
        client: String,
    },
    /// A WASM plugin.
    Plugin {
        /// The plugin ID.
        id: String,
    },
    /// A Python script.
    Python {
        /// The script name.
        script: String,
    },
    /// An importer applying a batch.
    Import {
        /// The import lineage ID, as text.
        lineage: String,
    },
    /// A merge.
    Merge,
    /// An external change (reload after a git pull, an edit by another program).
    External,
}

impl Origin {
    /// A short label for messages and the history panel: `gui`, `cli:<subcommand>`, `plugin:<id>`, ….
    pub fn label(&self) -> String {
        match self {
            Origin::Gui => "gui".into(),
            Origin::Cli { subcommand, .. } => format!("cli:{subcommand}"),
            Origin::CmdLog { file } => format!("cmdlog:{file}"),
            Origin::Script { name } => format!("script:{name}"),
            Origin::Mcp { client } => format!("mcp:{client}"),
            Origin::Plugin { id } => format!("plugin:{id}"),
            Origin::Python { script } => format!("python:{script}"),
            Origin::Import { lineage } => format!("import:{lineage}"),
            Origin::Merge => "merge".into(),
            Origin::External => "external".into(),
        }
    }
}
