// The rule notes

/// The hand-written notes of the shipped rules, one file per rule ID (CC-BY-4.0, outside the book's source).
const RULE_NOTES: &str = "docs/book/rule-notes";
/// The headings of a rule's notes, in this order, each with a non-empty section.
const NOTES_HEADINGS: [&str; 6] = [
    "What it checks",
    "Why",
    "Standard",
    "Example",
    "How to fix",
    "Waiving",
];
/// The one line of **Standard** for a rule that rests on no standard.
const NO_STANDARD: &str = "No standard: a project-hygiene rule.";
/// Golden A's expected findings: the EF rows (rule, count, subjects, targets, defect).
const GOLDEN_FINDINGS: &str = "crates/ew-api/tests/expected/findings_mvp.csv";

/// The notes files of [`RULE_NOTES`], by file name.
fn read_notes(root: &Path) -> Result<BTreeMap<String, String>> {
    let mut notes = BTreeMap::new();
    let Ok(entries) = std::fs::read_dir(root.join(RULE_NOTES)) else {
        return Ok(notes);
    };
    for entry in entries {
        let entry = entry.with_context(|| format!("reading {RULE_NOTES}"))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let text = read_lf(&entry.path())?.unwrap_or_default();
        notes.insert(name, text);
    }
    Ok(notes)
}

/// The section of `heading` (`## <heading>`) in a notes text: the line number of its heading (from 1) and its
/// body, trimmed; `None` when the heading is missing.
fn notes_section(text: &str, heading: &str) -> Option<(usize, String)> {
    let lines: Vec<&str> = text.lines().collect();
    let at = lines
        .iter()
        .position(|l| l.trim_end() == format!("## {heading}"))?;
    let body: Vec<&str> = lines[at + 1..]
        .iter()
        .take_while(|l| !l.starts_with("## "))
        .copied()
        .collect();
    Some((at + 1, body.join("\n").trim().to_owned()))
}

/// The problems of the rule notes (T1 to T4): a shipped rule without notes, a heading missing, empty or out of
/// order, a notes file for no shipped rule, and a line that quotes or cites a standard outside D7's form.
fn notes_problems(rules: &[Rule], notes: &BTreeMap<String, String>) -> Vec<String> {
    let mut problems = Vec::new();
    let files: BTreeSet<String> = rules.iter().map(|r| rule_file(&r.id)).collect();
    for file in &files {
        let Some(text) = notes.get(file) else {
            problems.push(format!(
                "{RULE_NOTES}/{file} is missing: every shipped rule needs its notes (NFR-DOC-02)"
            ));
            continue;
        };
        let mut after = 0;
        for heading in NOTES_HEADINGS {
            match notes_section(text, heading) {
                Some((line, body)) if line > after && !body.is_empty() => after = line,
                _ => problems.push(format!(
                    "{RULE_NOTES}/{file}: the section \"## {heading}\" is missing or empty"
                )),
            }
        }
        let standard = notes_section(text, "Standard").map_or(0, |(line, _)| line);
        let mut in_standard = false;
        for (i, line) in text.lines().enumerate() {
            if line.starts_with("## ") {
                in_standard = i + 1 == standard;
                continue;
            }
            let quoted = line.trim_start().starts_with('>');
            if quoted || (in_standard && !line.trim().is_empty() && !is_citation(line)) {
                problems.push(format!(
                    "{RULE_NOTES}/{file}:{}: cite a standard by number and clause only, as \"<body> \
                     <number>[:<year>], <clause>\" (NFR-COMP-05)",
                    i + 1
                ));
            }
        }
    }
    for name in notes.keys().filter(|n| !files.contains(*n)) {
        problems.push(format!("{RULE_NOTES}/{name} names no shipped rule"));
    }
    problems
}

/// Whether a line of **Standard** is a citation of D7's form, `<body> <number>[:<year>], <clause>` with an optional
/// note in brackets and an optional list marker, or [`NO_STANDARD`]: the body is upper-case words (`IEC`,
/// `ISO/IEC`, `EN`), the number digits and hyphens, the year four digits, and the clause a clause number, or `Annex`,
/// `Table` or `Figure` and its number, several joined by `and`; no quotation marks.
fn is_citation(line: &str) -> bool {
    let line = line.trim();
    let line = line.strip_prefix("- ").unwrap_or(line);
    if line == NO_STANDARD {
        return true;
    }
    if line.contains(['"', '“', '”', '„', '«', '»']) {
        return false;
    }
    let line = match line
        .strip_suffix(')')
        .and_then(|l| l.rfind(" (").map(|at| &l[..at]))
    {
        Some(head) => head,
        None => line,
    };
    let Some((head, clause)) = line.split_once(", ") else {
        return false;
    };
    let mut words: Vec<&str> = head.split(' ').collect();
    let Some(number) = words.pop() else {
        return false;
    };
    let (number, year) = number.split_once(':').unwrap_or((number, ""));
    let body_ok = !words.is_empty()
        && words
            .iter()
            .all(|w| !w.is_empty() && w.chars().all(|c| c.is_ascii_uppercase() || c == '/'));
    let number_ok = number.starts_with(|c: char| c.is_ascii_digit())
        && number.chars().all(|c| c.is_ascii_digit() || c == '-');
    let year_ok = year.is_empty() || (year.len() == 4 && year.chars().all(|c| c.is_ascii_digit()));
    let clause_number = |s: &str| {
        s.starts_with(|c: char| c.is_ascii_alphanumeric())
            && s.chars().any(|c| c.is_ascii_digit() || c.is_ascii_uppercase())
            && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '.')
    };
    let clause_ok = clause.split(" and ").all(|part| {
        let words: Vec<&str> = part.split(' ').collect();
        match words.as_slice() {
            [n] => clause_number(n) && n.starts_with(|c: char| c.is_ascii_digit()),
            [kind, n] => ["Annex", "Table", "Figure"].contains(kind) && clause_number(n),
            _ => false,
        }
    });
    body_ok && number_ok && year_ok && clause_ok
}

/// One EF row of Golden A's expected findings.
struct GoldenFinding {
    ef: String,
    rule: String,
    severity: String,
    count: String,
    subjects: String,
    targets: String,
    defect: String,
}

/// The EF rows of [`GOLDEN_FINDINGS`], in file order.
fn golden_findings(root: &Path) -> Result<Vec<GoldenFinding>> {
    let text =
        read_lf(&root.join(GOLDEN_FINDINGS))?.with_context(|| format!("{GOLDEN_FINDINGS} is missing"))?;
    let mut lines = text.lines().filter(|l| !l.trim().is_empty());
    let header = crate::repo::csv_fields(
        lines
            .next()
            .with_context(|| format!("{GOLDEN_FINDINGS} is empty"))?,
    );
    let column = |name: &str| {
        header
            .iter()
            .position(|h| h == name)
            .with_context(|| format!("{GOLDEN_FINDINGS} has no column `{name}`"))
    };
    let (ef, rule, severity, count) = (
        column("ef")?,
        column("rule")?,
        column("severity")?,
        column("count")?,
    );
    let (subjects, targets, defect) = (column("subjects")?, column("targets")?, column("defect")?);
    Ok(lines
        .map(|line| {
            let fields = crate::repo::csv_fields(line);
            let get = |i: usize| fields.get(i).cloned().unwrap_or_default();
            GoldenFinding {
                ef: get(ef),
                rule: get(rule),
                severity: get(severity),
                count: get(count),
                subjects: get(subjects),
                targets: get(targets),
                defect: get(defect),
            }
        })
        .collect())
}

