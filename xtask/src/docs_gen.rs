/// The `SUMMARY.md` text with the generated entries replaced: every line that links into a directory of `lists`
/// (`reference/commands/`, `reference/rules/`, `reference/cli/`, `reference/format/`) other than its index page is
/// dropped, then the entries are inserted, indented two spaces deeper, below the line that links the index page of
/// their directory.
fn rewrite_summary(text: &str, lists: &[(&str, &SummaryItems)]) -> Result<String> {
    let is_generated = |line: &str| {
        lists.iter().any(|(dir, _)| {
            let prefix = format!("]({dir}/");
            line.contains(&prefix) && !line.contains(&format!("]({dir}/index.md)"))
        })
    };
    let mut out = String::new();
    let mut seen = vec![false; lists.len()];
    for line in text.lines().filter(|l| !is_generated(l)) {
        out.push_str(line);
        out.push('\n');
        let indent = line.len() - line.trim_start().len();
        let Some(i) = lists
            .iter()
            .position(|(dir, _)| line.contains(&format!("({dir}/index.md)")))
        else {
            continue;
        };
        seen[i] = true;
        for (title, link, depth) in lists[i].1 {
            let _ = writeln!(out, "{}- [{title}]({link})", " ".repeat(indent + 2 + 2 * depth));
        }
    }
    if seen.contains(&false) {
        let indexes: Vec<String> = lists.iter().map(|(dir, _)| format!("{dir}/index.md")).collect();
        bail!("{BOOK_SRC}/{SUMMARY} must link {}", indexes.join(", "));
    }
    Ok(out)
}

