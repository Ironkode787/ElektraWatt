/// The `open_item` member of a catalogue rule.
#[derive(Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct OpenItem {
    category: String,
    discriminator: Option<String>,
}

impl OpenItem {
    /// The rule page's "Open item" cell for `item`: the category, with the discriminator when only some findings are.
    fn cell(item: Option<&OpenItem>) -> String {
        match item {
            None => "no".to_owned(),
            Some(OpenItem {
                category,
                discriminator: None,
            }) => cell(category),
            Some(OpenItem {
                category,
                discriminator: Some(d),
            }) => format!("{} (findings with discriminator `{d}` only)", cell(category)),
        }
    }
}

#[derive(Clone, Deserialize)]
#[serde(deny_unknown_fields)]
struct RuleScheme {
    name: String,
    online: bool,
    release: bool,
}

/// The rule catalogue snapshot; a field the mirror does not know is refused.
fn parse_catalogue(text: &str) -> Result<Catalogue> {
    serde_json::from_str(text).with_context(|| format!("parsing {CATALOGUE}"))
}

/// The rule pages: per pack an index page, per rule a page of its own, nested below its pack in
/// `SUMMARY.md`, and the rule reference's index. Returns the `SUMMARY.md` entries and the problems of the rule
/// notes (T1 to T4).
fn rule_pages(root: &Path, files: &mut BTreeMap<String, String>) -> Result<(SummaryItems, Vec<String>)> {
    let text = read_lf(&root.join(CATALOGUE))?.with_context(|| format!("{CATALOGUE} is missing"))?;
    let catalogue = parse_catalogue(&text)?;
    let notes = read_notes(root)?;
    let problems = notes_problems(&catalogue.rules, &notes);
    let findings = golden_findings(root)?;
    let mut packs: BTreeMap<&str, Vec<&Rule>> = BTreeMap::new();
    for rule in &catalogue.rules {
        packs.entry(rule.pack.as_str()).or_default().push(rule);
    }
    let mut items = SummaryItems::new();
    let mut rows = String::new();
    for (pack, rules) in &packs {
        let page = pack_page_path(pack);
        let file = page
            .strip_prefix(&format!("{RULES_DIR}/"))
            .unwrap_or(&page)
            .to_owned();
        files.insert(page.clone(), pack_page(pack, rules));
        items.push(((*pack).to_owned(), page, 0));
        for r in rules {
            let rule_page = rule_page_path(&r.id);
            if r.docs.as_str() != rule_page.trim_end_matches(".md") {
                bail!(
                    "{CATALOGUE}: {}: docs \"{}\" names no page docs-gen writes ({})",
                    r.id,
                    r.docs,
                    rule_page.trim_end_matches(".md")
                );
            }
            let note = notes.get(&rule_file(&r.id)).map(String::as_str).unwrap_or("");
            let mine: Vec<&GoldenFinding> = findings.iter().filter(|f| f.rule == r.id).collect();
            files.insert(rule_page.clone(), rule_page_text(r, note, &mine));
            items.push((r.id.clone(), rule_page, 1));
        }
        let _ = writeln!(
            rows,
            "| [`{pack}`]({file}) | {} | {} |",
            rules.len(),
            rules
                .iter()
                .map(|r| format!("[`{}`]({})", r.id, rule_file(&r.id)))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }

    let schemes: Vec<String> = catalogue
        .schemes
        .iter()
        .map(|s| {
            format!(
                "| `{}` | {} | {} |",
                s.name,
                cell(&s.purpose),
                if s.lenient { "yes" } else { "no" }
            )
        })
        .collect();
    let mut page = String::new();
    let _ = write!(
        page,
        "# Rule reference\n\n{}\n\n\
         A rule checks one property of a project and reports findings with the rule's ID, for example `EW-TERM-002`. \
         Rules are grouped in packs; a check scheme selects the rules a run executes. This reference lists the {} \
         shipped rules of the rule registry, one page per rule and an index page per pack, with the rule notes \
         [`{RULE_NOTES}`]({}). The rule catalogue of the design is \
         [doc 15 §4]({}).\n\n\
         A rule's page says what the rule checks and why, the standard it rests on by number and clause, its \
         finding in the golden project, how to fix a finding and whether a finding can be waived. F1 on a finding \
         in the Messages pane opens the page of its rule.\n\n\
         ## Packs\n\n| Pack | Rules | IDs |\n|---|---|---|\n{rows}\n\
         ## Schemes\n\n| Scheme | Purpose | Lenient |\n|---|---|---|\n{}\n",
        header("the rule registry and the rule notes"),
        catalogue.rules.len(),
        repo_tree_link(RULE_NOTES),
        repo_link(
            "docs/design/15-checks-revisions-collaboration.md",
            Some("4-rule-catalogue")
        ),
        schemes.join("\n"),
    );
    files.insert(format!("{RULES_DIR}/index.md"), page);
    Ok((items, problems))
}

/// The file name of a rule's page, as a link from a page of [`RULES_DIR`]: `ew-core-033.md`.
fn rule_file(id: &str) -> String {
    format!("{}.md", id.to_lowercase())
}

/// The index page of one rule pack: its rules, each linking its page.
fn pack_page(pack: &str, rules: &[&Rule]) -> String {
    let mut out = format!("# Rule pack {pack}\n\n{}\n\n", header("the rule registry"));
    let _ = write!(out, "{} rule(s) in this pack.", rules.len());
    if let Some((_, title, anchor)) = PACK_SECTIONS.iter().find(|(p, _, _)| p == &pack) {
        let _ = write!(
            out,
            " The catalogue entry of the pack is [doc 15 §{title}]({}).",
            repo_link("docs/design/15-checks-revisions-collaboration.md", Some(anchor)),
        );
    }
    out.push_str(
        "\n\n| ID | Title | Kind | Severity | Release severity | Modes | Scope |\n|---|---|---|---|---|---|---|\n",
    );
    for r in rules {
        let _ = writeln!(
            out,
            "| [`{}`]({}) | {} | {} | {} | {} | {} | {} |",
            r.id,
            rule_file(&r.id),
            cell(&r.title),
            r.kind,
            r.severity,
            r.release_severity.as_deref().unwrap_or("same"),
            r.modes.join(", "),
            r.scope,
        );
    }
    out
}

/// The page of one rule: the title; what it checks, why and the standard, from the rule's notes; its
/// findings in the golden project and the notes' example; how to fix (the hint, then the notes); waiving (from
/// `waivable`, then the notes); then the rule's data.
fn rule_page_text(r: &Rule, notes: &str, findings: &[&GoldenFinding]) -> String {
    let section = |heading: &str| {
        notes_section(notes, heading)
            .map(|(_, body)| body)
            .unwrap_or_default()
    };
    let mut golden = String::new();
    if findings.is_empty() {
        golden.push_str("Golden A has no finding of this rule.\n");
    }
    for f in findings {
        let subjects: Vec<String> = f
            .subjects
            .split("; ")
            .filter(|s| !s.is_empty())
            .map(|s| format!("`{s}`"))
            .collect();
        let state = if f.severity == "waived" {
            " waived".to_owned()
        } else {
            format!(", {}", f.severity)
        };
        let _ = write!(golden, "- {}: {} finding(s){state}", f.ef, f.count);
        if !subjects.is_empty() {
            let _ = write!(golden, ", on {}", subjects.join(", "));
        }
        if !f.targets.is_empty() {
            let _ = write!(golden, " ({})", cell(&f.targets));
        }
        if !f.defect.is_empty() {
            let _ = write!(golden, "; the golden project's defect {}", f.defect);
        }
        golden.push_str(".\n");
    }
    let supersedes: Vec<String> = r.supersedes.iter().map(|s| format!("`{s}`")).collect();
    let running = |online: bool| -> String {
        let names: Vec<String> = r
            .schemes
            .iter()
            .filter(|s| if online { s.online } else { s.release })
            .map(|s| format!("`{}`", s.name))
            .collect();
        if names.is_empty() {
            "none".to_owned()
        } else {
            names.join(", ")
        }
    };
    format!(
        "# {id} {title}\n\n{header}\n\n\
         Pack [{pack}]({pack_file}).\n\n\
         ## What it checks\n\n{checks}\n\n\
         ## Why\n\n{why}\n\n\
         ## Standard\n\n{standard}\n\n\
         ## In the golden project\n\n{golden}\n{example}\n\n\
         ## How to fix\n\n{hint}{fix}\n\n\
         ## Waiving\n\n{waivable}\n\n{waiving}\n\n\
         ## Rule data\n\n\
         | Item | Value |\n|---|---|\n\
         | ID | `{id}` |\n\
         | Code | `{code}` |\n\
         | Pack | `{pack}` |\n\
         | Kind | {kind} |\n\
         | Severity | {severity} |\n\
         | Release severity | {release_severity} |\n\
         | Modes | {modes} |\n\
         | Scope | {scope} |\n\
         | Waivable | {waivable_cell} |\n\
         | Pack content | {release} |\n\
         | Supersedes | {supersedes} |\n\
         | Open item | {open_item} |\n\
         | Runs in schemes, online mode | {online} |\n\
         | Runs in schemes, release mode | {release_mode} |\n",
        id = r.id,
        title = clean(&r.title),
        header = header(&format!(
            "the rule registry and {RULE_NOTES}/{}",
            rule_file(&r.id)
        )),
        pack = r.pack,
        pack_file = rule_file(&r.pack),
        checks = section("What it checks"),
        why = section("Why"),
        standard = section("Standard"),
        example = section("Example"),
        // An integrity rule has no hint: its finding carries the reader's own text.
        hint = if r.hint.is_empty() {
            String::new()
        } else {
            format!("{}\n\n", clean(&r.hint))
        },
        fix = section("How to fix"),
        waivable = if r.waivable {
            "This rule's findings can be waived."
        } else {
            "This rule's findings cannot be waived."
        },
        waiving = section("Waiving"),
        code = r.code,
        kind = r.kind,
        severity = r.severity,
        release_severity = r.release_severity.as_deref().unwrap_or("same as severity"),
        // An integrity rule runs when the project is opened (doc 15 §4.2's mode n), which no mode word names.
        modes = if r.kind == "integrity" {
            ["on open"]
                .into_iter()
                .chain(r.modes.iter().map(String::as_str))
                .collect::<Vec<_>>()
                .join(", ")
        } else {
            r.modes.join(", ")
        },
        scope = r.scope,
        waivable_cell = if r.waivable { "yes" } else { "no" },
        release = r.release,
        supersedes = if supersedes.is_empty() {
            "none".to_owned()
        } else {
            supersedes.join(", ")
        },
        open_item = OpenItem::cell(r.open_item.as_ref()),
        online = running(true),
        release_mode = running(false),
    )
}

