/// The line of a generated page that says where it comes from.
fn header(source: &str) -> String {
    format!(
        "<!-- Generated by `cargo xtask docs-gen` from {source}. Do not edit: change the source and regenerate. -->"
    )
}

/// The link to a repository directory.
fn repo_tree_link(path: &str) -> String {
    format!("{}{path}", REPO_BLOB.replace("/blob/", "/tree/"))
}

/// The link to a repository file, with an optional anchor.
fn repo_link(path: &str, anchor: Option<&str>) -> String {
    match anchor {
        Some(a) => format!("{REPO_BLOB}{path}#{a}"),
        None => format!("{REPO_BLOB}{path}"),
    }
}

/// Description text made safe for Markdown: rustdoc intra-doc links (`` [`X`] ``) become code spans, and `<`
/// outside code spans is escaped so that placeholders such as `<kind>` are not read as HTML.
fn clean(text: &str) -> String {
    let text = text.replace("[`", "`").replace("`]", "`");
    let mut out = String::with_capacity(text.len());
    let mut in_code = false;
    for c in text.chars() {
        match c {
            '`' => {
                in_code = !in_code;
                out.push(c);
            }
            '<' if !in_code => out.push_str("&lt;"),
            _ => out.push(c),
        }
    }
    out
}

/// Text for a table cell: one line, `|` escaped.
fn cell(text: &str) -> String {
    clean(text).replace('\n', " ").replace('|', "\\|")
}

/// The first paragraph of a description, on one line.
fn first_paragraph(text: &str) -> String {
    text.split("\n\n").next().unwrap_or("").replace('\n', " ")
}

/// The anchor `mdBook` gives a heading (lower case, punctuation dropped).
fn anchor(name: &str) -> String {
    name.chars()
        .filter(|c| c.is_alphanumeric() || *c == '-' || *c == '_' || *c == ' ')
        .collect::<String>()
        .to_lowercase()
        .replace(' ', "-")
}

/// The page of a command, relative to [`BOOK_SRC`]: `reference/commands/<name>.md`.
fn command_page_path(name: &str) -> String {
    format!("{COMMANDS_DIR}/{name}.md")
}

/// The page of a rule, relative to [`BOOK_SRC`]: `reference/rules/<id in lower case>.md`
/// (`reference/rules/ew-core-033.md`); the rule's `docs` reference is this path without `.md` (D6).
fn rule_page_path(id: &str) -> String {
    format!("{RULES_DIR}/{}.md", id.to_lowercase())
}

/// The index page of a rule pack, relative to [`BOOK_SRC`]: `reference/rules/<pack in lower case>.md`.
fn pack_page_path(pack: &str) -> String {
    format!("{RULES_DIR}/{}.md", pack.to_lowercase())
}

fn str_of<'a>(v: &'a Value, key: &str) -> &'a str {
    v.get(key).and_then(Value::as_str).unwrap_or("")
}

/// Joins words as "a, b or c".
fn join_or(items: &[String]) -> String {
    match items {
        [] => String::new(),
        [one] => one.clone(),
        [init @ .., last] => format!("{} or {last}", init.join(", ")),
    }
}

