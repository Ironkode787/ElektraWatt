//! `docs-gen`: the generated reference pages of the user documentation book (NFR-DOC-06).
//!
//! The sources are plain data files, so that this permissive-layer tool links no GPL crate. The first group is the
//! reference under `target/reference/`, which the product's own tests write when `cargo xtask gen` or
//! `cargo xtask docs-gen` asks (`generate.rs`); it is never committed:
//!
//! - `commands/`, the command-parameter JSON Schemas of `ew-commands`, give one page per command under
//!   `docs/book/src/reference/commands/`;
//! - `rules.json`, the rule catalogue of `ew-checks`, gives one page per rule and an index page per rule pack under
//!   `docs/book/src/reference/rules/`, each rule's page joining the rule's hand-written notes
//!   (`docs/book/rule-notes/`) and its findings in Golden A (`crates/ew-api/tests/expected/findings_mvp.csv`); a
//!   rule without notes, or notes that miss a section or cite a standard in another form, fail;
//! - `keymap-sheet.json` of `ew-viewmodel` gives `reference/keymaps.md`;
//! - `cli.json` of `ew` with its result schemas (`results/`) gives one page per first path word under
//!   `reference/cli/`; `queries.json` of `ew-api` gives `reference/queries.md`; `api_v1.json` of `ew-sqlview` gives
//!   `reference/api-v1.md`.
//!
//! The second group is committed:
//!
//! - the product glossary of `ew-viewmodel` (`crates/ew-viewmodel/glossary/glossary.toml`, the source of the command
//!   palette's aliases) gives `docs/book/src/reference/glossary.md`;
//! - the JSON Schemas of the project format (`schemas/0.1/`, written by `ew-schema`) give one page per record kind
//!   that has a schema under `reference/format/`, and its index of every kind;
//! - the release and migration notes of the releases (`docs/release-notes/<X.Y.Z>.md`, WP-S6.08's) give one page per
//!   release under `reference/release-notes/`, newest first, with their relative links rewritten to the repository's
//!   address, and the index of the releases;
//!
//! The generated pages are built, not committed: the root `.gitignore` names them (a test keeps its block equal to
//! [`GENERATED_DIRS`] and [`GENERATED_PAGES`]), and the contract files they render stay committed. `docs-gen` writes
//! them and removes a stale one; `--check` fails on a built page that git tracks. The four lists of generated entries in `docs/book/src/SUMMARY.md` are rewritten
//! too: every line that links into `reference/commands/`, `reference/rules/`, `reference/cli/` or
//! `reference/format/` (the index pages excepted) is regenerated below the line that links the index page.
//! `SUMMARY.md` stays committed, so `docs-gen --check` changes nothing and fails only when it differs.
//!
//! The pages hold what the sources hold: a command's description, registry entry and parameter types; a rule's
//! ID, code, title, hint, pack, kind, modes, severities, scope, supersessions and scheme membership, with the prose
//! of its notes (what it checks, why, the standard, an example, how to fix and waiving).

