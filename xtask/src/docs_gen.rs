/// The result schemas of `ew` by schema name (`ew.check-result/1`).
fn result_schemas(root: &Path) -> Result<BTreeMap<String, ResultSchema>> {
    let index = read_json(root, &format!("{RESULT_DIR}/index.json"))?;
    let entries = index
        .get("results")
        .and_then(Value::as_array)
        .with_context(|| format!("{RESULT_DIR}/index.json has no `results` list"))?;
    let mut out = BTreeMap::new();
    for entry in entries {
        let file = str_of(entry, "schema").to_owned();
        let schema = read_json(root, &format!("{RESULT_DIR}/{file}"))?;
        out.insert(str_of(entry, "name").to_owned(), (file, schema));
    }
    Ok(out)
}

/// One flag of a synopsis: `[--json]`, `[--out <out>]`, `[--company <company>]...`.
fn flag_synopsis(flag: &Value) -> String {
    let name = str_of(flag, "name");
    let inner = if flag.get("value").and_then(Value::as_bool) == Some(true) {
        format!("{name} <{}>", name.trim_start_matches('-'))
    } else {
        name.to_owned()
    };
    let more = if flag.get("repeatable").and_then(Value::as_bool) == Some(true) {
        "..."
    } else {
        ""
    };
    format!("[{inner}]{more}")
}

fn yes_no(v: Option<&Value>) -> &'static str {
    if v.and_then(Value::as_bool) == Some(true) {
        "yes"
    } else {
        "no"
    }
}

