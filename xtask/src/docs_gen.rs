/// The page of the subcommand paths under the first word `word`.
fn cli_group_page(
    word: &str,
    entries: &[&Value],
    results: &BTreeMap<String, ResultSchema>,
) -> Result<String> {
    let mut out = format!(
        "# `ew {word}`\n\n{}\n\n{} subcommand path(s). The synopsis lists the flags; `ew help` prints the positional \
         arguments too.\n\n",
        header("the catalogue of `ew` and its result schemas"),
        entries.len(),
    );
    for entry in entries {
        let path = str_of(entry, "path");
        let flags: Vec<&Value> = entry
            .get("flags")
            .and_then(Value::as_array)
            .map(|f| f.iter().collect())
            .unwrap_or_default();
        let synopsis: Vec<String> = flags.iter().map(|f| flag_synopsis(f)).collect();
        let _ = write!(
            out,
            "## `ew {path}`\n\n```text\new {path}{}{}\n```\n\nStability: {}.\n\n",
            if synopsis.is_empty() { "" } else { " " },
            synopsis.join(" "),
            str_of(entry, "stability"),
        );
        if flags.is_empty() {
            out.push_str("No flags.\n\n");
        } else {
            out.push_str("| Flag | Takes a value | Repeatable |\n|---|---|---|\n");
            for f in &flags {
                let _ = writeln!(
                    out,
                    "| `{}` | {} | {} |",
                    str_of(f, "name"),
                    yes_no(f.get("value")),
                    yes_no(f.get("repeatable")),
                );
            }
            out.push('\n');
        }
        out.push_str("**Exit codes**\n\n| Code | Meaning |\n|---|---|\n");
        for x in entry.get("exits").and_then(Value::as_array).into_iter().flatten() {
            let _ = writeln!(
                out,
                "| {} | {} |",
                x.get("code").map_or_else(String::new, Value::to_string),
                cell(str_of(x, "meaning")),
            );
        }
        out.push('\n');
        let Some(name) = entry.get("result").and_then(Value::as_str) else {
            out.push_str("**Result:** none; the subcommand prints text only.\n\n");
            continue;
        };
        let (_, schema) = results
            .get(name)
            .with_context(|| format!("{CLI_SNAPSHOT}: `ew {path}` names the result {name}, which {RESULT_DIR}/index.json does not list"))?;
        let _ = write!(
            out,
            "**Result** (`--json`): `{name}`; `ew schema {name}` prints its schema.\n\n",
        );
        let (table, types) = fields_and_types(schema);
        if let Some(table) = table {
            out.push_str(&table);
            out.push('\n');
        }
        out.push_str(&types);
    }
    Ok(out)
}

