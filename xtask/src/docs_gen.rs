/// The entries a generated page list adds to `SUMMARY.md`: link text, path relative to the book source, and the depth
/// below the index page (0 for a page of the list, 1 for a page nested under the entry before it).
type SummaryItems = Vec<(String, String, usize)>;

/// Everything `docs-gen` writes.
struct Generated {
    /// Page path relative to [`BOOK_SRC`] to its text.
    files: BTreeMap<String, String>,
    commands: SummaryItems,
    packs: SummaryItems,
    cli: SummaryItems,
    format: SummaryItems,
    releases: SummaryItems,
    /// The problems of the rule notes (T1 to T4) and of the glossary pages (T7).
    notes: Vec<String>,
}

impl Generated {
    /// The generated page lists of `SUMMARY.md`, in [`GENERATED_DIRS`] order.
    fn lists(&self) -> [(&'static str, &SummaryItems); 5] {
        [
            (COMMANDS_DIR, &self.commands),
            (RULES_DIR, &self.packs),
            (CLI_DIR, &self.cli),
            (FORMAT_DIR, &self.format),
            (RELEASE_NOTES_DIR, &self.releases),
        ]
    }
}

/// What `docs-gen` would write.
struct Plan {
    /// Page path relative to [`BOOK_SRC`] to its wanted text, `SUMMARY.md` included.
    wanted: BTreeMap<String, String>,
    /// The pages whose text on disk differs or is missing.
    differing: Vec<String>,
    /// The pages on disk in the generated directories that no source gives.
    stale: Vec<String>,
    /// The documents outside the book with a generated part (relative to the root) whose text differs, with their
    /// wanted text.
    partial: Vec<(String, String)>,
    commands: usize,
    packs: usize,
    /// The problems of the rule notes (T1 to T4) and of the glossary pages (T7), reported by both modes.
    notes: Vec<String>,
}

fn plan(root: &Path) -> Result<Plan> {
    let generated = generate(root)?;
    let mut wanted: BTreeMap<String, String> = generated.files.clone();
    let summary_path = root.join(BOOK_SRC).join(SUMMARY);
    let summary =
        read_lf(&summary_path)?.with_context(|| format!("{} is missing", summary_path.display()))?;
    wanted.insert(SUMMARY.to_owned(), rewrite_summary(&summary, &generated.lists())?);
    let (differing, stale) = compare(root, &wanted)?;
    // No document outside the book has a generated part at present.
    let partial = Vec::new();
    Ok(Plan {
        wanted,
        differing,
        stale,
        partial,
        commands: generated.commands.len(),
        packs: generated.packs.iter().filter(|(_, _, depth)| *depth == 0).count(),
        notes: generated.notes,
    })
}

/// The wanted pages whose text on disk under `root` differs or is missing, and the pages on disk in the generated
/// directories that `wanted` does not hold.
fn compare(root: &Path, wanted: &BTreeMap<String, String>) -> Result<(Vec<String>, Vec<String>)> {
    let mut differing = Vec::new();
    for (rel, text) in wanted {
        if read_lf(&root.join(BOOK_SRC).join(rel))?.as_deref() != Some(text.as_str()) {
            differing.push(rel.clone());
        }
    }
    let mut stale = Vec::new();
    for dir in GENERATED_DIRS {
        let Ok(entries) = std::fs::read_dir(root.join(BOOK_SRC).join(dir)) else {
            continue;
        };
        for entry in entries.flatten() {
            let rel = format!("{dir}/{}", entry.file_name().to_string_lossy());
            if !wanted.contains_key(&rel) {
                stale.push(rel);
            }
        }
    }
    stale.sort();
    Ok((differing, stale))
}

/// Whether a page (relative to [`BOOK_SRC`]) is built, not committed: in a generated directory, or a generated
/// single page.
fn is_built(rel: &str) -> bool {
    GENERATED_PAGES.contains(&rel)
        || GENERATED_DIRS
            .iter()
            .any(|dir| rel.strip_prefix(dir).is_some_and(|rest| rest.starts_with('/')))
}

/// The violations of `docs-gen --check` (NFR-DOC-06): one per committed page (`SUMMARY.md`) that differs or is
/// missing, per built page that git tracks (`tracked`, from [`tracked_built`]: a file under [`GENERATED_DIRS`] or one
/// of [`GENERATED_PAGES`], added with `git add -f`, say), and per document outside the book whose generated part
/// differs. The built pages are not committed, so an absent, old or stray untracked one is no violation.
fn violations_of(differing: &[String], tracked: &[String], partial: &[(String, String)]) -> Vec<String> {
    let differing = differing
        .iter()
        .filter(|rel| !is_built(rel))
        .map(|rel| format!("{BOOK_SRC}/{rel} differs; run `cargo xtask docs-gen`"));
    let tracked = tracked.iter().map(|rel| {
        format!("{BOOK_SRC}/{rel} is a built page, but git tracks it; run `git rm --cached {BOOK_SRC}/{rel}`")
    });
    let partial = partial
        .iter()
        .map(|(rel, _)| format!("{rel}: its generated part differs; run `cargo xtask docs-gen`"));
    differing.chain(tracked).chain(partial).collect()
}

/// The built pages that git tracks, relative to [`BOOK_SRC`] (`git ls-files`): the tracked files under
/// [`GENERATED_DIRS`] and the tracked [`GENERATED_PAGES`].
fn tracked_built(root: &Path) -> Result<Vec<String>> {
    let mut args = vec!["ls-files".to_owned(), "-z".to_owned(), "--".to_owned()];
    args.extend(GENERATED_DIRS.iter().map(|dir| format!("{BOOK_SRC}/{dir}/")));
    args.extend(GENERATED_PAGES.iter().map(|page| format!("{BOOK_SRC}/{page}")));
    let args: Vec<&str> = args.iter().map(String::as_str).collect();
    let prefix = format!("{BOOK_SRC}/");
    Ok(crate::repo::nul_paths(&crate::repo::git_output(root, &args)?)
        .into_iter()
        .filter_map(|f| f.strip_prefix(&prefix).map(str::to_owned))
        .filter(|rel| is_built(rel))
        .collect())
}

/// `docs-gen [--check]` for the repository at `root`.
pub(crate) fn run(root: &Path, check: bool) -> Result<bool> {
    let plan = plan(root)?;
    if check {
        let mut violations = violations_of(&plan.differing, &tracked_built(root)?, &plan.partial);
        violations.extend(plan.notes);
        if violations.is_empty() {
            println!(
                "docs-gen: ok ({} commands, {} rule packs)",
                plan.commands, plan.packs
            );
            return Ok(true);
        }
        eprintln!("docs-gen: {} problem(s)", violations.len());
        for v in &violations {
            eprintln!("  - {v}");
        }
        return Ok(false);
    }

    for rel in &plan.differing {
        let path = root.join(BOOK_SRC).join(rel);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        }
        std::fs::write(&path, &plan.wanted[rel]).with_context(|| format!("writing {}", path.display()))?;
    }
    for rel in &plan.stale {
        let path = root.join(BOOK_SRC).join(rel);
        std::fs::remove_file(&path).with_context(|| format!("removing {}", path.display()))?;
    }
    for (rel, text) in &plan.partial {
        crate::repo::write_atomic(&root.join(rel), text)?;
    }
    println!(
        "docs-gen: {} page(s) written, {} removed, {} unchanged; {} generated part(s) outside the book written",
        plan.differing.len(),
        plan.stale.len(),
        plan.wanted.len() - plan.differing.len(),
        plan.partial.len()
    );
    if !plan.notes.is_empty() {
        eprintln!(
            "docs-gen: {} problem(s) in the rule notes and the glossary pages",
            plan.notes.len()
        );
        for v in &plan.notes {
            eprintln!("  - {v}");
        }
        return Ok(false);
    }
    Ok(true)
}

/// The text of a file with LF line ends; `None` when it does not exist.
fn read_lf(path: &Path) -> Result<Option<String>> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(Some(text.replace("\r\n", "\n"))),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

/// Reads and parses a JSON file under `root`.
fn read_json(root: &Path, rel: &str) -> Result<Value> {
    let text = read_lf(&root.join(rel))?.with_context(|| format!("{rel} is missing"))?;
    serde_json::from_str(&text).with_context(|| format!("parsing {rel}"))
}

fn generate(root: &Path) -> Result<Generated> {
    let mut files = BTreeMap::new();
    let commands = command_pages(root, &mut files)?;
    let (packs, notes) = rule_pages(root, &mut files)?;
    files.insert(GLOSSARY_PAGE.to_owned(), glossary_page(root)?);
    let mut notes = notes;
    notes.extend(glossary_sections(root)?);
    files.insert(
        KEYMAPS_PAGE.to_owned(),
        keymaps_text(&read_json(root, KEYMAP_SHEET)?)?,
    );
    let results = result_schemas(root)?;
    let cli = cli_pages(&read_json(root, CLI_SNAPSHOT)?, &results, &mut files)?;
    files.insert(QUERIES_PAGE.to_owned(), queries_text(&read_json(root, QUERIES)?)?);
    files.insert(API_V1_PAGE.to_owned(), api_v1_text(&read_json(root, API_V1)?)?);
    let format = format_pages(root, &mut files)?;
    let releases = release_note_pages(root, &mut files)?;
    Ok(Generated {
        files,
        commands,
        packs,
        cli,
        format,
        releases,
        notes,
    })
}

