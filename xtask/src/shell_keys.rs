//! The shell's text-key list (WP-S2.08 part 3, ID-1219 ruling 3): `crates/ew-viewmodel/src/strings/keys.rs`, the
//! message IDs of the en-GB `shell.ftl` in file order, which `key!` and `count_key!` check at compile time. A settle
//! step writes it; `--check` changes nothing and fails when the committed file differs. No build script.

use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};

/// The en-GB Fluent file of the shell, the source of the list.
pub(crate) const SOURCE: &str = "crates/ew-viewmodel/locales/en-GB/shell.ftl";
/// The generated key list.
pub(crate) const OUTPUT: &str = "crates/ew-viewmodel/src/strings/keys.rs";

/// The message IDs of the Fluent source `ftl` in file order: each line that starts an entry `<id> =` (a term starts
/// with `-`, a comment with `#`, a continuation with a space; none is a message).
fn message_ids(ftl: &str) -> Vec<&str> {
    ftl.lines()
        .filter_map(|line| {
            let (id, _) = line.split_once(" =")?;
            let mut chars = id.chars();
            let good = chars.next().is_some_and(|c| c.is_ascii_alphabetic())
                && chars.all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
            good.then_some(id)
        })
        .collect()
}

/// The text of the key list for the Fluent source `ftl`.
fn render(ftl: &str) -> Result<String> {
    let mut s = String::new();
    s.push_str(concat!(
        "// SPDX",
        "-FileCopyrightText: 2026 The ElektraWatt contributors\n",
        "// SPDX",
        "-License-Identifier: GPL-3.0-or-later\n",
    ));
    s.push_str(
        "\n\
         // Generated by `cargo xtask settle` from locales/en-GB/shell.ftl; do not edit. `cargo xtask settle --check`\n\
         // fails when it is stale.\n\
         \n\
         /// Every text key of the shell, in the order of the en-GB file: the keys `key!` and `count_key!` check at\n\
         /// compile time.\n\
         pub const KEYS: &[&str] = &[\n",
    );
    for id in message_ids(ftl) {
        writeln!(s, "    {id:?},")?;
    }
    s.push_str("];\n");
    Ok(s)
}

/// The wanted text of the key list for the repository at `root`.
fn generate(root: &Path) -> Result<String> {
    let path = root.join(SOURCE);
    let ftl = std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    render(&ftl.replace("\r\n", "\n"))
}

/// The key list's step for the repository at `root`: writes it, or with `check` reports whether it is current.
pub(crate) fn run(root: &Path, check: bool) -> Result<bool> {
    let wanted = generate(root)?;
    let path = root.join(OUTPUT);
    if check {
        let have = std::fs::read_to_string(&path)
            .ok()
            .map(|t| t.replace("\r\n", "\n"));
        if have.as_deref() == Some(wanted.as_str()) {
            println!("shell-keys: ok");
            return Ok(true);
        }
        eprintln!("shell-keys: {OUTPUT} differs from {SOURCE}; run `cargo xtask settle`");
        return Ok(false);
    }
    std::fs::write(&path, wanted).with_context(|| format!("writing {}", path.display()))?;
    println!("shell-keys: wrote {OUTPUT}");
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A message starts its line; a comment, a term, an attribute and a continuation are no message.
    #[test]
    fn the_keys_are_the_message_ids_in_order() {
        let ftl = "# c = d\nmenu-file = File\n-term = T\n    .attr = A\n  cont = x\nchip-library = # library · { $p0 }\n";
        assert_eq!(message_ids(ftl), ["menu-file", "chip-library"]);
        let out = render(ftl).unwrap();
        assert!(
            out.ends_with("pub const KEYS: &[&str] = &[\n    \"menu-file\",\n    \"chip-library\",\n];\n"),
            "{out}"
        );
    }

    /// The committed list is current.
    #[test]
    fn the_committed_list_is_current() {
        assert!(run(&crate::workspace_root(), true).unwrap());
    }
}
